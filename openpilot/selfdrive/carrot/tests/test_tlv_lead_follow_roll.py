# R6-R8: the arm fires on the red, ends with the red, resets on a dropout.
# ---------------------------------------------------------------------------

def roll_in(planner, frames: int, red: bool):
  for step in range(frames):
    planner.tlv_red_active = red
    tick(planner, lead(d_rel=7.0 + 0.075 * (step + 1), v_lead=3.0), 1.5)


def test_r6_fires_when_the_red_arrives():
  planner = tlv_planner(red=False)
  roll_in(planner, 20, red=False)  # 1.0 s of pull-away before any red
  assert planner.lead_follow_active is False

  planner.tlv_red_active = True
  d_rel = 7.0 + 0.075 * 21
  tick(planner, lead(d_rel=d_rel, v_lead=3.0), 1.5)
  assert planner.lead_follow_active is True, "the latch did not fire on the first red frame"
  assert planner.coast_cap_active is False


def test_r7_ends_with_the_red():
  planner = tlv_planner(red=False)
  roll_in(planner, 20, red=False)
  planner.tlv_red_active = True
  d_rel = 7.0 + 0.075 * 21
  tick(planner, lead(d_rel=d_rel, v_lead=3.0), 1.5)
  assert planner.lead_follow_active is True

  planner.tlv_red_active = False
  tick(planner, lead(d_rel=d_rel + 0.075, v_lead=3.0), 1.5)
  assert planner.lead_follow_active is False
  assert planner.lead_follow_roll_frames == 0
  assert planner.lead_follow_roll_d0 is None


def test_r8_dropout_resets_the_count():
  planner = tlv_planner()  # red on throughout
  for step in range(9):  # 0.45 s pulling away, still short of 0.5 s
    tick(planner, lead(d_rel=7.0 + 0.1 * (step + 1), v_lead=3.0), 1.5)
  assert planner.lead_follow_roll_frames == 9
  tick(planner, lead(status=False, d_rel=7.9), 1.5)  # one-frame lead dropout
  assert planner.lead_follow_roll_frames == 0
  for step in range(6):  # 0.30 s pulling away: the count starts over
    tick(planner, lead(d_rel=7.9 + 0.1 * (step + 1), v_lead=3.0), 1.5)
  assert planner.lead_follow_roll_frames == 6
  assert planner.lead_follow_active is False
