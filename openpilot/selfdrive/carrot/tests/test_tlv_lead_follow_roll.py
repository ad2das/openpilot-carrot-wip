def test_r2_no_fire_without_pull_away():
  planner = tlv_planner()
  for step in range(60):  # 3 s, dRel 6 -> 10 m, dv 0.9 m/s
    tick(planner, lead(d_rel=6.0 + 4.0 * step / 59, v_lead=2.4), 1.5)
  assert planner.lead_follow_active is False
  assert planner.coast_cap_active is True


def test_r3_no_fire_too_fast():
  planner = tlv_planner()
  for step in range(60):  # 3 s, ego 3.0 == LEAD_FOLLOW_ROLL_V_MAX
    tick(planner, lead(d_rel=8.0 + 4.0 * step / 59, v_lead=4.5), 3.0)
  assert planner.lead_follow_active is False


def test_r4_no_fire_too_far():
  planner = tlv_planner()
  for step in range(60):  # 3 s, dRel 15.5 -> 20 m: outside the 15 m arm distance
    tick(planner, lead(d_rel=15.5 + 4.5 * step / 59, v_lead=3.0), 1.5)
  assert planner.lead_follow_active is False


def test_r5_no_fire_when_gap_closed():
  planner = tlv_planner()
  for _ in range(40):  # 2 s, the gap never opens (d gain < 0.5 m)
    tick(planner, lead(d_rel=8.0, v_lead=2.6), 1.5)
  assert planner.lead_follow_active is False


