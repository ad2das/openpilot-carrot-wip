def tlv_planner(mode: int = 2, red: bool = True):
  """The shared skeleton plus the rolling-arm state (:301-308 in __init__)."""
  planner = base_tlv_planner(mode, red)
  planner.lead_follow_roll_frames = 0
  planner.lead_follow_roll_d0 = None
  return planner


# ---------------------------------------------------------------------------
# R1: the field window, replayed frame by frame.
# ---------------------------------------------------------------------------

def test_r1_real_rows_latch_on_roll():
  assert len(ROLL1_ROWS) == 121
  assert sum(row[5] for row in ROLL1_ROWS) == 57

  planner = tlv_planner(red=False)
  prev_red = False
  seen = []  # (t_rel, prev_red, active, cap)
  for t_rel, v_ego, status, d_rel, v_lead, red in ROLL1_ROWS:
    planner.tlv_red_active = prev_red  # premise 5: one-frame lag
    tick(planner, lead(status=bool(status), d_rel=d_rel, v_lead=v_lead), v_ego)
    seen.append((t_rel, prev_red, planner.lead_follow_active, planner.coast_cap_active))
    prev_red = bool(red)

  first = next(t for t, _, active, _ in seen if active)
  assert first <= 0.95, f"the latch armed late, at t_rel {first}"
  assert not any(active for t, _, active, _ in seen if t < 0.85), \
    "the latch armed before the red appeared"

  latched = [(t, cap) for t, prev_red, active, cap in seen if prev_red and t >= first]
  assert len(latched) == 57, f"{len(latched)} latched rows, expected 57"
  assert not any(cap for _, cap in latched), "the coast cap held the car while latched"


