def freeze_man(monkeypatch):
  monkeypatch.setattr(carrot_man_input.time, "monotonic", lambda: 100.0)


def man_planner(monkeypatch, left=False, active=True):
  freeze_man(monkeypatch)
  planner = planner_for_gate(False)
  planner.trafficState = TrafficState.green
  planner.trafficLightDetectMode = 2
  planner.tlv_red_active = True
  planner.lead_follow_active = active
  planner.lead_follow_arm_frames = 0
  planner.lead_follow_d_stop = None
  planner.lead_follow_d_prev = 0.0
  planner._update_carrot_man(gate_sm(carrot_man_message(state=1, src=1), left=left), 20.0, 60.0)
  return planner


def test_veto_and_stay_stop_lifted_while_active(monkeypatch):
  held = man_planner(monkeypatch, active=False)
  assert held.tlv_red_veto is True
  assert held._model_green_start_allowed() is False

  follow = man_planner(monkeypatch, active=True)
  assert follow.tlv_red_veto is False
  assert follow._model_green_start_allowed() is True

  # Left intent: the TLV red keeps the stop while the latch is off, and the
  # departing lead releases it (a lead that turns right on red).
  held_left = man_planner(monkeypatch, left=True, active=False)
  assert held_left.carrot_stay_stop is True
  follow_left = man_planner(monkeypatch, left=True, active=True)
  assert follow_left.carrot_stay_stop is False


