K5_FIRE = "13:21:43.901"


def lead(status=True, d_rel=5.0, v_lead=0.0):
  return SimpleNamespace(status=status, dRel=d_rel, vLead=v_lead)


def tlv_planner(mode: int = 2, red: bool = True):
  """A planner skeleton that can run _update_lead_follow and _update_coast_cap."""
  planner = planner_for_gate(False)
  planner.trafficLightDetectMode = mode
  planner.tlv_red_active = red
  planner.tlv_gas_cooldown_frames = 0
  planner.lead_follow_active = False
  planner.lead_follow_arm_frames = 0
  planner.lead_follow_d_stop = None
  planner.lead_follow_d_prev = 0.0
  return planner


def tick(planner, row_lead, v_ego: float) -> None:
  """One carrot update() frame: the latch first, then the coast cap (:1131/:1187)."""
  planner._update_lead_follow(row_lead, v_ego)
  planner._update_coast_cap(v_ego)


def fire(planner, d_stop: float = 5.0) -> None:
  """Stand stopped 1 s behind a lead at d_stop, then let it drive off."""
  for _ in range(LEAD_FOLLOW_ARM_FRAMES):
    tick(planner, lead(d_rel=d_stop, v_lead=0.0), 0.0)
  for step in range(1, 12):
    tick(planner, lead(d_rel=d_stop + 0.15 * step + 0.5, v_lead=1.5), 0.0)
    if planner.lead_follow_active:
      return
  raise AssertionError("the latch never fired")


