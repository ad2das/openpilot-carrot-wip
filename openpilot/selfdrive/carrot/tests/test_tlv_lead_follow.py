def test_ends_when_lead_lost():
  planner = tlv_planner()
  fire(planner)
  assert planner.coast_cap_active is False
  tick(planner, lead(status=False, d_rel=6.0), 0.0)
  assert planner.lead_follow_active is False
  assert planner.coast_cap_active is True  # TLV red still on -> the cap is back


def test_ends_on_lead_jump():
  planner = tlv_planner()
  fire(planner)
  d_before = planner.lead_follow_d_prev
  tick(planner, lead(d_rel=d_before + 6.0, v_lead=1.5), 0.0)  # a different object
  assert planner.lead_follow_active is False
  assert planner.coast_cap_active is True


def test_ends_when_tlv_red_ends():
  planner = tlv_planner()
  fire(planner)
  assert planner.lead_follow_active is True
  # :1180 refreshes tlv_red_active before the next frame's latch check (:1131).
  planner.tlv_red_active = False
  tick(planner, lead(d_rel=8.0, v_lead=1.5), 0.0)
  assert planner.lead_follow_active is False
  assert planner.coast_cap_active is False  # the cap needs the red too


