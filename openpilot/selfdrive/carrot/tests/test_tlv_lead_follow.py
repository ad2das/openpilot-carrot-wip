# The field event: 13:21:27.0-44.4, the real radar rows.
# ---------------------------------------------------------------------------

def test_k5_1321_real_rows_fire_at_43901():
  planner = tlv_planner()
  seen = []
  for kst, v_ego, lead_ok, d_rel, v_lead in K5_ROWS:
    tick(planner, lead(bool(lead_ok), d_rel, v_lead), v_ego)
    seen.append((kst, planner.lead_follow_active, planner.coast_cap_active))

  fired = [kst for kst, active, _ in seen if active]
  assert fired, "the lead-follow latch never fired on the K5 rows"
  assert fired[0] == K5_FIRE, f"first latch tick {fired[0]}, expected {K5_FIRE}"
  # Nothing before the fire: the lead was still slow or too close to gain 0.5 m.
  assert all(not active for kst, active, _ in seen if kst < K5_FIRE)

  # The cap holds the car from the moment the red is on until the lead departs ...
  early = [cap for kst, _, cap in seen if "13:21:28.5" <= kst < K5_FIRE]
  assert len(early) > 100, f"only {len(early)} ticks before the fire"
  assert all(early), "the coast cap was off before the lead departed"
  # ... and drops on the very tick the latch fires, staying off while it is latched.
  late = [(kst, cap) for kst, active, cap in seen if kst >= K5_FIRE]
  assert all(active for kst, active, _ in seen if kst >= K5_FIRE)
  assert not any(cap for _, cap in late), "the coast cap came back while the latch was active"


